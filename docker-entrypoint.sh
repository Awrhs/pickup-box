#!/bin/sh
# Container start-up (runs as root before nginx):
#  1. make sure the data directory exists and the worker user can write it,
#     also when /data is a freshly bind-mounted host directory;
#  2. when the app sits behind a reverse proxy (TRUST_X_FORWARDED_FOR=true,
#     set by deploy/docker-compose.yml), let nginx take the client address
#     from X-Forwarded-For so per-IP rate limits apply per real client and
#     not to the proxy as a whole.
set -e
DATA_DIR="${IMAGE_DATA_DIR:-/data/images}"
mkdir -p "$DATA_DIR/orig" "$DATA_DIR/cache" "$DATA_DIR/tmp"
chown pickup:pickup "$DATA_DIR" "$DATA_DIR/orig" "$DATA_DIR/cache" "$DATA_DIR/tmp"

REALIP=/usr/local/openresty/nginx/conf/realip.conf
case "${TRUST_X_FORWARDED_FOR:-false}" in
    true|1|yes)
        cat > "$REALIP" <<'CONF'
# Generated by docker-entrypoint.sh (TRUST_X_FORWARDED_FOR=true): requests
# come from a reverse proxy on a private network.
set_real_ip_from 10.0.0.0/8;
set_real_ip_from 172.16.0.0/12;
set_real_ip_from 192.168.0.0/16;
set_real_ip_from fc00::/7;
real_ip_header X-Forwarded-For;
real_ip_recursive on;
CONF
        ;;
    *)
        : > "$REALIP"
        ;;
esac

exec "$@"
